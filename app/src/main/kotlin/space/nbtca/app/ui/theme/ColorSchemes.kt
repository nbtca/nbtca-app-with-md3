internal fun ThemePalette.colorScheme(darkTheme: Boolean): ColorScheme {
    val palette = when (this) {
        ThemePalette.NbtcaBlue -> blue
        ThemePalette.Forest -> forest
        ThemePalette.Lilac -> lilac
        ThemePalette.Amber -> amber
        ThemePalette.Rose -> rose
        ThemePalette.Graphite -> graphite
    }
    return if (darkTheme) palette.dark else palette.light
}

